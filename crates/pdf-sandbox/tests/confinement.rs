/// A JBIG2 stream the codec spends minutes on is ended at the worker's deadline, and the next
/// request is answered.
///
/// The `jbig2` fuzz target's input (ADR 1424): an 85-byte `/JBIG2Globals` stream whose symbol
/// dictionary `hayro-jbig2` spends minutes decoding. The codec is a dependency and runs
/// confined, so the time budget principle 3 asks for is the parent's `REQUEST_TIMEOUT`, not a bound
/// inside the decoder: this test is that the budget holds on an input that needs it — a typed
/// [`SandboxError::TimedOut`] well inside twice the deadline — and that the worker replaced after it
/// answers. Framed as the fuzz target reads it: a two-byte length, the globals, the segments.
#[test]
fn a_decode_that_does_not_return_is_ended_at_the_deadline() {
    let framed = A_SYMBOL_DICTIONARY_OF_MINUTES;
    let (length, rest) = framed.split_at(2);
    let split = usize::from(u16::from_be_bytes([length[0], length[1]])).min(rest.len());
    let (globals, data) = rest.split_at(split);
    let sandbox = Sandbox::shared();

    let started = std::time::Instant::now();
    let error = sandbox
        .decode(&Request::Jbig2 { data, globals })
        .unwrap_err();
    let spent = started.elapsed();
    assert!(
        matches!(error, SandboxError::TimedOut),
        "a decode past the deadline is refused as one: {error}"
    );
    assert!(
        spent < std::time::Duration::from_mins(1),
        "and it is refused at the deadline, not after the decode: {spent:?}"
    );
    assert!(
        sandbox.decode(&request()).is_ok(),
        "the next request is answered"
    );
}

