/// A `/FunctionType 4` returning `red = x`, `green = y`, `blue = 0` over the unit square.
///
/// The two inputs are already on the stack when the program starts (§7.10.5), so pushing one
/// zero leaves exactly the three values the `/Range` asks for. A two-input function has to be
/// a stream — Table 38's exponential and stitching types take one input each — which is why
/// this is the one fixture here that needs an extra object.
const DOMAIN_AS_COLOUR: &str = "7 0 obj\n<< /FunctionType 4 /Domain [0 1 0 1] \
                                /Range [0 1 0 1 0 1] /Length 5 >>\nstream\n{ 0 }\n\
                                endstream\nendobj\n";

/// ISO 32000-2 §8.7.4.5.2, Table 78: a type 1 shading's `/Matrix` places its domain.
///
/// > Matrix … An array of six numbers specifying a transformation matrix mapping the
/// > coordinate space specified by the Domain entry into the shading's target coordinate
/// > space.
///
/// The function is the identity on the domain, so every pixel names the domain point it came
/// from — which turns "is the matrix applied, and the right way round" into an assertion about
/// two pixels rather than about a gradient's appearance. The second half is the one that
/// discriminates: translating the matrix by half the page must move the colours by half the
/// page, and a reader that ignores `/Matrix` altogether draws the domain's unit square into
/// one point at the page's corner and leaves the rest of it flat.
#[test]
fn a_function_based_shading_maps_its_domain_through_its_matrix() {
    let shading = |matrix: &str| {
        format!(
            "<< /ShadingType 1 /ColorSpace /DeviceRGB /Domain [0 1 0 1] \
             /Matrix {matrix} /Function 7 0 R >>"
        )
    };

    // The domain covers the whole 100x100 page. Device row 0 is the page's *top*, so a
    // device y of 25 is a domain y of 0.75.
    let across = render(pdf_with_extra(
        &shading("[100 0 0 100 0 0]"),
        "/Sh0 sh",
        DOMAIN_AS_COLOUR,
    ));
    let (red, green, blue, alpha) = pixel(&across, 25, 25);
    assert_eq!(alpha, 255, "the shading paints the whole clip");
    assert_eq!(blue, 0, "the function's third output is a constant zero");
    assert!(
        (60..=70).contains(&red),
        "red is the domain's x at a quarter across the page, got {red}"
    );
    assert!(
        (185..=195).contains(&green),
        "green is the domain's y, which is 0.75 a quarter *down* the page, got {green}"
    );

    // The same shading with its domain pushed half a page to the right: the colour a quarter
    // across the page must now be the one that was at the page's left edge.
    let shifted = render(pdf_with_extra(
        &shading("[100 0 0 100 50 0]"),
        "/Sh0 sh",
        DOMAIN_AS_COLOUR,
    ));
    let (shifted_red, _, _, _) = pixel(&shifted, 75, 25);
    assert_eq!(
        shifted_red, red,
        "translating the matrix by half the page moves the colours by half the page"
    );
}
