//! Public rendered-pixel regression for ordinary RGB JPX opacity channels.
//!
//! The JP2 containers were generated with Pillow 13.0.0's `OpenJPEG` encoder in reversible mode;
//! `doc/reviews/2038-specification-audit/shards/images_current/generate_jpx.py` regenerates both byte arrays and records their SHA-256
//! hashes. Each has a 2x1 four-channel lossless codestream, sRGB color declaration, and `cdef`
//! that associates channels 0..2 with R/G/B and channel 3 with the whole image (association 0).
//! ISO/IEC 15444-1 I.5.3.6 Table I-16 defines cdef kind 1 as opacity and kind 2 as premultiplied
//! opacity. The code-2 fixture changes only that cdef kind and carries color bytes multiplied by
//! alpha. ISO 32000-2 §7.4.9 says nonzero `SMaskInData` has one opacity channel applied to all color
//! channels; Table 87 defines code 1 as opacity and code 2 as premultiplied color. The PDF
//! dictionaries state `/ColorSpace /DeviceRGB`, dimensions matching `ihdr`, and no `/SMask`, so
//! both nonzero combinations satisfy the producer constraints being tested.
//!
//! Independent expected values: code 1 retains straight RGB [255,0,0] / [0,0,255] with alpha
//! 128/64. Code 2 divides premultiplied [128,0,0] / [0,0,64] by 128/255 and 64/255, restoring
//! full red / blue while preserving those alpha levels. Code 0 with the type-1 opacity channel
//! ignores it and must paint fully opaque RGB, per Table 87. Each assertion checks the public
//! CPU raster output at the two source-cell centers.

#![expect(
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::arithmetic_side_effects,
    reason = "small exact fixtures; invalid data or an out-of-range output pixel should fail loudly"
)]

