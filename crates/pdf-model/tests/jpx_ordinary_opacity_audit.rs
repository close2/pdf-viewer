fn image_pdf(jp2: &[u8], smask_in_data: u8) -> Vec<u8> {
    let content = b"q 40 0 0 20 0 0 cm /Im Do Q";
    let mut objects = vec![
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n".to_vec(),
        b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n".to_vec(),
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 40 20] /Resources << /XObject << /Im 5 0 R >> >> /Contents 4 0 R >>\nendobj\n".to_vec(),
    ];
    let mut page_stream =
        format!("4 0 obj\n<< /Length {} >>\nstream\n", content.len()).into_bytes();
    page_stream.extend_from_slice(content);
    page_stream.extend_from_slice(b"\nendstream\nendobj\n");
    objects.push(page_stream);
    let mut image = format!(
        "5 0 obj\n<< /Type /XObject /Subtype /Image /Width 2 /Height 1 /ColorSpace /DeviceRGB /Filter /JPXDecode /SMaskInData {smask_in_data} /Length {} >>\nstream\n",
        jp2.len()
    ).into_bytes();
    image.extend_from_slice(jp2);
    image.extend_from_slice(b"\nendstream\nendobj\n");
    objects.push(image);

    let mut file = b"%PDF-1.7\n%\xE2\xE3\xCF\xD3\n".to_vec();
    let mut offsets = Vec::new();
    for object in objects {
        offsets.push(file.len());
        file.extend_from_slice(&object);
    }
    let xref = file.len();
    let size = offsets.len() + 1;
    let mut table = String::new();
    let _ = writeln!(table, "xref\n0 {size}");
    table.push_str("0000000000 65535 f \n");
    for offset in offsets {
        let _ = writeln!(table, "{offset:010} 00000 n ");
    }
    let _ = write!(
        table,
        "trailer\n<< /Size {size} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n"
    );
    file.extend_from_slice(table.as_bytes());
    file
}

fn render(jp2: &[u8], smask_in_data: u8) -> pdf_render::Raster {
    let bytes = image_pdf(jp2, smask_in_data);
    let document = Document::open(bytes).expect("complete PDF with valid JP2 image");
    assert!(!document.was_recovered(), "PDF xref offsets are exact");
    assert!(!document.cross_reference_chain_was_cut());
    let page = pdf_model::Pages::new(&document).get(0).expect("one page");
    let interpretation = pdf_model::interpret(&document, &page);
    assert!(
        interpretation.is_complete(),
        "valid fixture: {:?}",
        interpretation.unsupported
    );
    let target =
        TargetSpec::for_page(&interpretation.display_list, 1.0, GENEROUS).expect("small target");
    CpuRasterizer::new()
        .with_medium(pdf_render::Medium::NONE)
        .rasterize(&interpretation.display_list, target)
        .expect("supported JPX raster")
}

fn rgba(raster: &pdf_render::Raster, x: u32, y: u32) -> [u8; 4] {
    let row = raster.height - 1 - y;
    let at = usize::try_from((row * raster.width + x) * 4).expect("bounded pixel offset");
    [
        raster.data[at],
        raster.data[at + 1],
        raster.data[at + 2],
        raster.data[at + 3],
    ]
}

fn assert_zero_control() {
    // Separate Table 87 code-0 control: it ignores the type-1 opacity channel and leaves RGB
    // fully opaque. Each nonzero-code regression rechecks this positive control first.
    let ignored = render(JP2_STRAIGHT_ALPHA, 0);
    assert_eq!(
        rgba(&ignored, 10, 10),
        [255, 0, 0, 255],
        "code 0 ignores opacity"
    );
    assert_eq!(
        rgba(&ignored, 30, 10),
        [0, 0, 255, 255],
        "code 0 keeps RGB fully opaque"
    );
}

#[test]
fn ordinary_rgb_jpx_smask_in_data_zero_ignores_the_opacity_channel() {
    assert_zero_control();
}

#[test]
fn ordinary_rgb_jpx_smask_in_data_one_uses_straight_alpha() {
    assert_zero_control();
    let straight = render(JP2_STRAIGHT_ALPHA, 1);
    assert_eq!(
        rgba(&straight, 10, 10),
        [255, 0, 0, 128],
        "code 1 red with half opacity"
    );
    assert_eq!(
        rgba(&straight, 30, 10),
        [0, 0, 255, 64],
        "code 1 blue with quarter opacity"
    );
}

#[test]
fn ordinary_rgb_jpx_smask_in_data_two_unpremultiplies_color() {
    assert_zero_control();
    let premultiplied = render(JP2_PREMULTIPLIED_ALPHA, 2);
    assert_eq!(
        rgba(&premultiplied, 10, 10),
        [255, 0, 0, 128],
        "code 2 restores red then keeps alpha"
    );
    assert_eq!(
        rgba(&premultiplied, 30, 10),
        [0, 0, 255, 64],
        "code 2 restores blue then keeps alpha"
    );
}
