#!/usr/bin/env python3
"""Writes the EPSG Dataset subset ISO 32000-2 section 12.10.3 resolves a numeric code through.

ADR 3821 is the decision and the layout; the owner's answer `doc/questions/A1095` is why the
registry is carried at all. Run as

    python3 -I -B tools/epsg-table.py --fetch
    python3 -I -B tools/epsg-table.py [--source <data/sql dir>] [--out <file>] [--check]

The first downloads PROJ's release archive of the tag `PROJ_TAG` names from download.osgeo.org into
`$PDF_VIEWER_SCRATCH/epsg/` (default `~/scratch/epsg/`), refuses it unless its SHA-256 is
`PROJ_SHA256`, and unpacks only its `data/sql/`. The second reads those SQL files -- PROJ's own
export of the EPSG Dataset, generated by PROJ's `scripts/build_db.py` -- and writes
`crates/pdf-model/src/geospatial/epsg/dataset.rs`; with `--check` it writes nothing and exits 1
where the file in the tree is not byte for byte what it would write. The archive is never committed.

**What is taken.** Every geographic 2D and 3D system of the EPSG authority, every projected system
over one of them, and what those name: their datums (datum ensembles included), ellipsoids, prime
meridians, the conversions of the projected systems with their method and every parameter, the
units any of these is stated in, and the projection methods' names. Deprecated codes are kept: a
code names the system it named when a file was written, and a document written before the
deprecation is as conforming as one written after it. Geocentric, vertical, compound and
engineering systems are not taken: section 12.10.3's `/GCS` is a geographic or a projected system.

**Values unchanged** (IOGP's terms of use, `LICENSE-EPSG`): every number is written as the SQL text
states it, so a parameter stated in sexagesimal DMS stays a sexagesimal DMS number and is converted
where it is read, never here. Only a whole number gains `.0`, the spelling a Rust `f64` literal
needs.

**Parameters past the seventh.** PROJ's `conversion` table has seven parameter slots, and Krovak
Modified and its North Orientated form (methods 1042 and 1043, Guidance Note 7-2 sections 3.1.2.3
and 3.1.2.4) state nineteen: the evaluation point (8617, 8618) and C1 to C10 (1026 to 1035) are
not in PROJ's export at all. Those twelve are read from IOGP's own registry, the EPSG Dataset's
public API (`REGISTRY_URL`, no account and no form), one record per conversion, which `--fetch`
saves under `$PDF_VIEWER_SCRATCH/epsg/registry/` (ADR 3897). A record is refused unless the
SHA-256 of its parameter list (one `code value unit` line each, in the record's order, every
number as the API's text spells it) is the one `REGISTRY_SHA256` pins, and unless its first
seven parameters are PROJ's seven, code, value and unit. A used conversion of either method that
`REGISTRY_SHA256` does not name stops the generator by its code.
"""

import argparse
import hashlib
import io
import json
import os
import sys
import tarfile
import urllib.request
from pathlib import Path

PROJ_TAG = "9.9.0"
PROJ_URL = f"https://download.osgeo.org/proj/proj-{PROJ_TAG}.tar.gz"
PROJ_SHA256 = "791a0610547eeabb17006cfd49cdbd2034f3240f47ed5e88a1031811f4e2bcf3"
EPSG_VERSION = "v13.102"

# The methods whose conversions state parameters past PROJ's seven slots, and the registry
# records that carry them, each pinned by the digest of its parameter list (see the docstring).
REGISTRY_METHODS = {1042, 1043}
REGISTRY_URL = "https://apps.epsg.org/api/v1/Conversion/{code}/"
REGISTRY_SHA256 = {
    5219: "fd558013fe2c74d6908ca9b742339a7577b4ccf4411bb3e25d6b724f676477fe",
    5220: "fd558013fe2c74d6908ca9b742339a7577b4ccf4411bb3e25d6b724f676477fe",
    5511: "e9c27eac1b3bd97e5de6156e9a7730812106133ec92f4c379460f56b889d7f44",
    5512: "e9c27eac1b3bd97e5de6156e9a7730812106133ec92f4c379460f56b889d7f44",
}

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates/pdf-model/src/geospatial/epsg/dataset.rs"


def cache_dir() -> Path:
    scratch = os.environ.get("PDF_VIEWER_SCRATCH") or str(Path.home() / "scratch")
    return Path(scratch) / "epsg"


def default_source() -> Path:
    return cache_dir() / f"proj-{PROJ_TAG}" / "data" / "sql"


def registry_dir() -> Path:
    return cache_dir() / "registry"


def registry_parameters(directory: Path, conversion: int) -> list:
    """One conversion's parameters from its saved registry record, as `(code, value text, unit)`
    in the record's order, refused unless their digest is the pinned one."""
    path = directory / f"conversion-{conversion}.json"
    record = json.loads(path.read_text(encoding="utf-8"), parse_float=str, parse_int=str)
    found = [
        (int(p["ParameterCode"]), p["ParameterValue"], int(p["Unit"]["Code"]))
        for p in sorted(record["ParameterValues"], key=lambda p: int(p["SortOrder"]))
    ]
    canonical = "".join(f"{c} {v} {u}\n" for c, v, u in found)
    digest = hashlib.sha256(canonical.encode("utf-8")).hexdigest()
    if digest != REGISTRY_SHA256[conversion]:
        sys.exit(f"{path}: parameter list SHA-256 {digest}, not the pinned {REGISTRY_SHA256[conversion]}")
    return found


def fetch() -> None:
    """Downloads the pinned archive, checks its digest, and unpacks `data/sql/` only; then saves
    the registry records `REGISTRY_SHA256` names and checks theirs."""
    target = cache_dir()
    target.mkdir(parents=True, exist_ok=True)
    archive = target / f"proj-{PROJ_TAG}.tar.gz"
    if not archive.exists():
        with urllib.request.urlopen(PROJ_URL) as response:
            archive.write_bytes(response.read())
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != PROJ_SHA256:
        sys.exit(f"{archive}: SHA-256 {digest}, not the pinned {PROJ_SHA256}")
    prefix = f"proj-{PROJ_TAG}/data/sql/"
    with tarfile.open(archive) as tar:
        members = [
            m for m in tar.getmembers()
            if m.name.startswith(prefix) and m.isfile() and m.name.endswith(".sql")
            and "/" not in m.name[len(prefix):]
        ]
        tar.extractall(target, members=members, filter="data")
    registry = registry_dir()
    registry.mkdir(parents=True, exist_ok=True)
    for conversion in sorted(REGISTRY_SHA256):
        path = registry / f"conversion-{conversion}.json"
        if not path.exists():
            request = urllib.request.Request(
                REGISTRY_URL.format(code=conversion), headers={"User-Agent": "epsg-table.py"}
            )
            with urllib.request.urlopen(request) as response:
                path.write_bytes(response.read())
        registry_parameters(registry, conversion)
    print(default_source())


def values(line: str) -> list:
    """The fields of one `INSERT INTO "t" VALUES(...);` line: a quoted string, None for NULL,
    or a number kept as its text."""
    start = line.index("VALUES(") + len("VALUES(")
    body = line[start:line.rindex(");")]
    out, i = [], 0
    while i < len(body):
        while body[i] == " ":
            i += 1
        c = body[i]
        if c == "'":
            j, text = i + 1, []
            while True:
                if body[j] == "'" and j + 1 < len(body) and body[j + 1] == "'":
                    text.append("'")
                    j += 2
                elif body[j] == "'":
                    break
                else:
                    text.append(body[j])
                    j += 1
            out.append("".join(text))
            i = j + 1
        else:
            j = body.find(",", i)
            j = len(body) if j < 0 else j
            token = body[i:j].strip()
            out.append(None if token == "NULL" else ("#", token))
            i = j
        if i < len(body):
            if body[i] != ",":
                raise ValueError(f"unexpected {body[i]!r} in {line[:80]}")
            i += 1
    return out


def rows(source: Path, file: str, table: str, width: int) -> list:
    marker = f'INSERT INTO "{table}" VALUES('
    found = []
    for line in (source / file).read_text(encoding="utf-8").splitlines():
        if line.startswith(marker):
            fields = values(line)
            if len(fields) != width:
                raise ValueError(f"{file}: {len(fields)} fields, expected {width}: {line[:80]}")
            found.append(fields)
    return found


def number(field) -> str:
    """A number as the SQL states it, spelled as a Rust `f64` literal."""
    kind, text = field
    assert kind == "#", field
    if not any(c in text for c in ".eE"):
        text += ".0"
    return text


def code(field) -> int:
    return int(field[1] if isinstance(field, tuple) else field)


def rust_str(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(source: Path, registry: Path) -> str:
    metadata = {r[0]: r[1] for r in rows(source, "metadata.sql", "metadata", 2)}
    if metadata.get("EPSG.VERSION") != EPSG_VERSION:
        sys.exit(f"{source}: EPSG {metadata.get('EPSG.VERSION')}, not the pinned {EPSG_VERSION}")

    epsg = lambda r: r[0] == "EPSG"  # noqa: E731
    units = {code(r[1]): r for r in rows(source, "unit_of_measure.sql", "unit_of_measure", 7) if epsg(r)}
    ellipsoids = {code(r[1]): r for r in rows(source, "ellipsoid.sql", "ellipsoid", 12) if epsg(r)}
    meridians = {code(r[1]): r for r in rows(source, "prime_meridian.sql", "prime_meridian", 7) if epsg(r)}
    datums = {code(r[1]): r for r in rows(source, "geodetic_datum.sql", "geodetic_datum", 14) if epsg(r)}
    axes: dict = {}
    for r in rows(source, "axis.sql", "axis", 10):
        if r[5] == "EPSG":
            axes.setdefault(code(r[6]), []).append((code(r[7]), r[4], r[8], r[9]))
    geodetic = rows(source, "geodetic_crs.sql", "geodetic_crs", 11)
    projected_rows = rows(source, "projected_crs.sql", "projected_crs", 12)
    conversions = {code(r[1]): r for r in rows(source, "conversion.sql", "conversion", 50) if epsg(r)}

    used_units: set = set()

    def axis_unit(cs: int) -> int:
        stated = {(a[2], code(a[3])) for a in axes[cs] if a[3] is not None}
        if len({u for _, u in stated}) != 1 or any(auth != "EPSG" for auth, _ in stated):
            raise ValueError(f"coordinate system {cs} states {stated}")
        return next(iter(stated))[1]

    geographic = {}
    for r in geodetic:
        if epsg(r) and r[4] in ("geographic 2D", "geographic 3D") and r[7] == "EPSG" and r[5] == "EPSG":
            cs = code(r[6])
            ordered = sorted(axes[cs])
            # The angular unit is the latitude's and the longitude's; a 3D system's height is the
            # third axis, in a length unit, and is not read.
            unit = {code(a[3]) for a in ordered[:2]}
            assert len(unit) == 1, (r[1], ordered)
            geographic[code(r[1])] = (r[2], code(r[8]), unit.pop())

    projected = {}
    for r in projected_rows:
        if not (epsg(r) and r[6] == "EPSG" and r[8] == "EPSG" and r[4] == "EPSG"):
            continue
        base = code(r[7])
        if base not in geographic or code(r[9]) not in conversions:
            continue
        cs = code(r[5])
        projected[code(r[1])] = (r[2], base, code(r[9]), axis_unit(cs))

    used_datums = {g[1] for g in geographic.values()}
    used_ellipsoids = {code(datums[d][5]) for d in used_datums}
    used_meridians = {code(datums[d][7]) for d in used_datums}
    used_conversions = {p[2] for p in projected.values()}
    methods = {}
    for c in used_conversions:
        r = conversions[c]
        methods[code(r[5])] = r[6]
    used_units |= {g[2] for g in geographic.values()}
    used_units |= {p[3] for p in projected.values()}
    used_units |= {code(ellipsoids[e][8]) for e in used_ellipsoids}
    used_units |= {code(meridians[m][5]) for m in used_meridians}
    def parameters(c: int) -> list:
        """A conversion's parameters as `(code, Rust literal, unit)`: PROJ's seven slots, and
        for the methods past them the registry's record from the eighth on."""
        r = conversions[c]
        found = []
        for k in range(7):
            base = 7 + 6 * k
            if r[base + 1] is None or r[base + 3] is None:
                continue
            found.append((code(r[base + 1]), number(r[base + 3]), code(r[base + 5])))
        if code(r[5]) not in REGISTRY_METHODS:
            return found
        if c not in REGISTRY_SHA256:
            sys.exit(
                f"conversion {c}: method {code(r[5])} states parameters past PROJ's seven, "
                "and no registry record is pinned"
            )
        stated = registry_parameters(registry, c)
        head = [(p, float(v), u) for p, v, u in stated[: len(found)]]
        if head != [(p, float(v), u) for p, v, u in found]:
            sys.exit(f"conversion {c}: the registry's first parameters {head} are not PROJ's {found}")
        return found + [(p, number(("#", v)), u) for p, v, u in stated[len(found):]]

    for c in used_conversions:
        used_units |= {u for _, _, u in parameters(c)}

    out = io.StringIO()
    w = out.write
    w("// The EPSG Dataset subset ISO 32000-2 section 12.10.3 resolves a code through, written by\n")
    w("// tools/epsg-table.py from PROJ " + PROJ_TAG + "'s data/sql (EPSG Dataset " + EPSG_VERSION + ",\n")
    w(f"// {metadata.get('EPSG.DATE')}). Generated: edit the script, never this file (ADR 3821).\n")
    w("//\n// The EPSG Dataset is owned by the International Association of Oil & Gas Producers (IOGP)\n")
    w("// and is used here under its terms of use, which LICENSE-EPSG carries; its values are\n")
    w("// unchanged.\n\n")
    w("use super::{\n    Conversion, Datum, Figure, Geographic, Meridian, Method, Parameter, Projected,\n")
    w("    Spheroid, Unit, UnitKind,\n};\n\n")
    w(f"/// The EPSG Dataset version this table was written from, as PROJ's metadata states it.\npub const VERSION: &str = {rust_str(EPSG_VERSION)};\n\n")

    w("/// Units of measure, by code.\npub(super) static UNITS: &[Unit] = &[\n")
    for c in sorted(used_units):
        r = units[c]
        kind = {"length": "Length", "angle": "Angle", "scale": "Scale"}[r[3]]
        factor = "None" if r[4] is None else f"Some({number(r[4])})"
        w(f"    Unit({c}, UnitKind::{kind}, {factor}, {rust_str(r[2])}),\n")
    w("];\n\n")

    w("/// Ellipsoids, by code: the semi-major axis, its unit, and the second parameter.\n")
    w("pub(super) static ELLIPSOIDS: &[Spheroid] = &[\n")
    for c in sorted(used_ellipsoids):
        r = ellipsoids[c]
        if r[9] is not None:
            figure = f"Figure::InverseFlattening({number(r[9])})"
        else:
            figure = f"Figure::SemiMinorAxis({number(r[10])})"
        w(f"    Spheroid({c}, {number(r[6])}, {code(r[8])}, {figure}),\n")
    w("];\n\n")

    w("/// Prime meridians, by code: the longitude from Greenwich and its unit.\n")
    w("pub(super) static PRIME_MERIDIANS: &[Meridian] = &[\n")
    for c in sorted(used_meridians):
        r = meridians[c]
        w(f"    Meridian({c}, {number(r[3])}, {code(r[5])}),\n")
    w("];\n\n")

    w("/// Geodetic datums and datum ensembles, by code: the ellipsoid and the prime meridian.\n")
    w("pub(super) static DATUMS: &[Datum] = &[\n")
    for c in sorted(used_datums):
        r = datums[c]
        w(f"    Datum({c}, {rust_str(r[2])}, {code(r[5])}, {code(r[7])}),\n")
    w("];\n\n")

    w("/// Geographic 2D and 3D systems, by code: the datum and the angular unit.\n")
    w("pub(super) static GEOGRAPHIC: &[Geographic] = &[\n")
    for c in sorted(geographic):
        name, datum, unit = geographic[c]
        w(f"    Geographic({c}, {rust_str(name)}, {datum}, {unit}),\n")
    w("];\n\n")

    w("/// Projection methods named by a conversion below, by code.\npub(super) static METHODS: &[Method] = &[\n")
    for c in sorted(methods):
        w(f"    Method({c}, {rust_str(methods[c])}),\n")
    w("];\n\n")

    w("/// Conversions, by code: the method and each parameter's code, value and unit.\n")
    w("pub(super) static CONVERSIONS: &[Conversion] = &[\n")
    for c in sorted(used_conversions):
        params = [f"Parameter({p}, {v}, {u})" for p, v, u in parameters(c)]
        w(f"    Conversion({c}, {code(conversions[c][5])}, &[{', '.join(params)}]),\n")
    w("];\n\n")

    w("/// Projected systems over a geographic one, by code: the base, the conversion, the unit of\n")
    w("/// the axes.\npub(super) static PROJECTED: &[Projected] = &[\n")
    for c in sorted(projected):
        name, base, conversion, unit = projected[c]
        w(f"    Projected({c}, {rust_str(name)}, {base}, {conversion}, {unit}),\n")
    w("];\n")

    print(
        f"units {len(used_units)} ellipsoids {len(used_ellipsoids)} meridians {len(used_meridians)} "
        f"datums {len(used_datums)} geographic {len(geographic)} methods {len(methods)} "
        f"conversions {len(used_conversions)} projected {len(projected)}",
        file=sys.stderr,
    )
    return out.getvalue()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fetch", action="store_true", help="download and unpack the pinned archive")
    parser.add_argument("--source", type=Path, default=None, help="PROJ's data/sql directory")
    parser.add_argument("--registry", type=Path, default=None, help="the saved registry records")
    parser.add_argument("--out", type=Path, default=OUT)
    parser.add_argument("--check", action="store_true", help="compare with --out, write nothing")
    args = parser.parse_args()
    if args.fetch:
        fetch()
        return
    text = generate(args.source or default_source(), args.registry or registry_dir())
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != text:
            sys.exit(f"{args.out} is not what PROJ {PROJ_TAG}'s data/sql generates")
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
