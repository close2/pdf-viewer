#!/usr/bin/env python3
"""Generate a valid s5 PDF with distinct StmF and StrF filters and independently derived keys.

Run from any directory:
  python3 scratchpad/r2038/spec-audit/structured_errata_security_current/dual_public_key_default_filters/generate_fixture.py DISTINCT.pdf SHARED_CONTROL.pdf

Requires openssl and the checked-in testnutzer X.509 DER certificate. CMS values are generated by
OpenSSL; the PDF's expected plaintext is literal and does not use the Rust reader as an oracle.
This is a draft fixture generator, not a claimed execution or conformance result.
"""

from __future__ import annotations

import hashlib
import pathlib
import subprocess
import sys
import tempfile


ROOT = next(parent for parent in pathlib.Path(__file__).resolve().parents if (parent / "Cargo.toml").exists())
CERT_DER = ROOT / "crates/pdf-syntax/tests/public_key_witnesses/testnutzer.certificate.der"
KEY_DER = ROOT / "crates/pdf-syntax/tests/public_key_witnesses/testnutzer.key.der"


def run(*args: str, input: bytes | None = None) -> bytes:
    return subprocess.run(args, input=input, check=True, stdout=subprocess.PIPE).stdout


def recipient_cms(cert_pem: pathlib.Path, seed: bytes, permission_word: bytes, work: pathlib.Path, stem: str) -> bytes:
    plain = work / f"{stem}.seed-permissions"
    cms = work / f"{stem}.cms.der"
    plain.write_bytes(seed + permission_word)
    run(
        "openssl", "cms", "-encrypt", "-binary", "-aes-128-cbc", "-in", str(plain),
        "-outform", "DER", "-out", str(cms), str(cert_pem),
    )
    return cms.read_bytes()


def object_key(file_key: bytes, number: int, generation: int = 0) -> bytes:
    material = (
        file_key
        + number.to_bytes(3, "little")
        + generation.to_bytes(2, "little")
        + b"sAlT"
    )
    return hashlib.md5(material).digest()[: min(len(file_key) + 5, 16)]


def encrypt_aesv2(plain: bytes, key: bytes, iv: bytes) -> bytes:
    return iv + run(
        "openssl", "enc", "-aes-128-cbc", "-K", key.hex(), "-iv", iv.hex(), input=plain
    )


def hex_string(data: bytes) -> bytes:
    return b"<" + data.hex().upper().encode("ascii") + b">"


def make_pdf(
    stm_cms: bytes,
    stm_key: bytes,
    str_cms: bytes,
    str_key: bytes,
    *,
    shared_default: bool = False,
) -> bytes:
    content = b"BT /F1 12 Tf 20 50 Td (Stream key) Tj ET"
    stream_cipher = encrypt_aesv2(content, object_key(stm_key, 4), bytes(range(16)))
    language_cipher = encrypt_aesv2(b"fr-FR", object_key(str_key, 1), bytes(range(16, 32)))

    stream_cms = hex_string(stm_cms)
    string_cms = hex_string(str_cms)
    if shared_default:
        filters = (
            b"/CF << /SameCF << /Type /CryptFilter /CFM /AESV2 /Length 128 /Recipients ["
            + stream_cms
            + b"] >> >> /StmF /SameCF /StrF /SameCF"
        )
    else:
        filters = (
            b"/CF << /StreamCF << /Type /CryptFilter /CFM /AESV2 /Length 128 /Recipients ["
            + stream_cms
            + b"] >> /StringCF << /Type /CryptFilter /CFM /AESV2 /Length 128 /Recipients ["
            + string_cms
            + b"] >> >> /StmF /StreamCF /StrF /StringCF"
        )
    objects = [
        b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R /Lang " + hex_string(language_cipher) + b" >>\nendobj\n",
        b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n",
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 100 100] /Resources << /Font << /F1 6 0 R >> >> /Contents 4 0 R >>\nendobj\n",
        b"4 0 obj\n<< /Length " + str(len(stream_cipher)).encode() + b" >>\nstream\n" + stream_cipher + b"\nendstream\nendobj\n",
        b"5 0 obj\n<< /Filter /Adobe.PubSec /SubFilter /adbe.pkcs7.s5 /V 4 "
        + filters
        + b" >>\nendobj\n",
        b"6 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n",
    ]

    pdf = bytearray(b"%PDF-1.7\n%\xE2\xE3\xCF\xD3\n")
    offsets = [0]
    for body in objects:
        offsets.append(len(pdf))
        pdf.extend(body)
    xref_at = len(pdf)
    pdf.extend(f"xref\n0 {len(offsets)}\n".encode())
    pdf.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        pdf.extend(f"{offset:010d} 00000 n \n".encode())
    pdf.extend(
        f"trailer\n<< /Size {len(offsets)} /Root 1 0 R /Encrypt 5 0 R /ID [<00112233445566778899AABBCCDDEEFF> <00112233445566778899AABBCCDDEEFF>] >>\nstartxref\n{xref_at}\n%%EOF\n".encode()
    )
    result = bytes(pdf)
    # Independently check the exact classic-xref offsets emitted above rather than
    # relying only on the reader under test to accept the fixture.
    assert result[xref_at : xref_at + 5] == b"xref\n"
    for object_number, offset in enumerate(offsets[1:], start=1):
        assert result[offset :].startswith(f"{object_number} 0 obj\n".encode())
    startxref_line = result.rsplit(b"startxref\n", 1)[1].splitlines()[0]
    assert int(startxref_line) == xref_at
    xref_lines = result[xref_at:].splitlines()
    assert xref_lines[1] == f"0 {len(offsets)}".encode()
    for line_number, offset in enumerate(offsets[1:], start=3):
        line = xref_lines[line_number]
        assert int(line[:10]) == offset and line[10:] == b" 00000 n "
    return result


def verify_envelope_and_payload(
    cms: bytes,
    seed: bytes,
    permissions: bytes,
    cert_pem: pathlib.Path,
    key_pem: pathlib.Path,
    file_key: bytes,
    number: int,
    plaintext: bytes,
    iv: bytes,
    work: pathlib.Path,
    label: str,
) -> None:
    cms_path = work / f"{label}.cms.der"
    cipher_path = work / f"{label}.ciphertext"
    cms_path.write_bytes(cms)
    assert run(
        "openssl", "cms", "-decrypt", "-binary", "-inform", "DER", "-in", str(cms_path),
        "-recip", str(cert_pem), "-inkey", str(key_pem),
    ) == seed + permissions

    ciphertext = encrypt_aesv2(plaintext, object_key(file_key, number), iv)
    cipher_path.write_bytes(ciphertext[16:])
    assert run(
        "openssl", "enc", "-d", "-aes-128-cbc", "-K", object_key(file_key, number).hex(),
        "-iv", iv.hex(), "-in", str(cipher_path),
    ) == plaintext


def main(distinct_output: pathlib.Path, shared_output: pathlib.Path) -> None:
    with tempfile.TemporaryDirectory(prefix="s5-dual-defaults-") as directory:
        work = pathlib.Path(directory)
        cert_pem = work / "recipient.pem"
        key_pem = work / "recipient-key.pem"
        run("openssl", "x509", "-inform", "DER", "-in", str(CERT_DER), "-out", str(cert_pem))
        run("openssl", "pkey", "-inform", "DER", "-in", str(KEY_DER), "-out", str(key_pem))

        # Same recipient and permissions, but distinct seeds and CMS DER, hence distinct keys.
        permissions = bytes.fromhex("fffffff4")
        stm_seed = bytes(range(1, 21))
        str_seed = bytes(range(21, 41))
        stm_cms = recipient_cms(cert_pem, stm_seed, permissions, work, "stream")
        str_cms = recipient_cms(cert_pem, str_seed, permissions, work, "string")
        stm_key = hashlib.sha1(stm_seed + stm_cms).digest()[:16]
        str_key = hashlib.sha1(str_seed + str_cms).digest()[:16]
        if stm_key == str_key:
            raise RuntimeError("the two default filters must derive distinct keys")
        content = b"BT /F1 12 Tf 20 50 Td (Stream key) Tj ET"
        verify_envelope_and_payload(
            stm_cms, stm_seed, permissions, cert_pem, key_pem, stm_key, 4,
            content, bytes(range(16)), work, "stream",
        )
        verify_envelope_and_payload(
            str_cms, str_seed, permissions, cert_pem, key_pem, str_key, 1,
            b"fr-FR", bytes(range(16, 32)), work, "string",
        )
        distinct_output.write_bytes(make_pdf(stm_cms, stm_key, str_cms, str_key))

        shared_seed = bytes(range(41, 61))
        shared_cms = recipient_cms(cert_pem, shared_seed, permissions, work, "shared")
        shared_key = hashlib.sha1(shared_seed + shared_cms).digest()[:16]
        verify_envelope_and_payload(
            shared_cms, shared_seed, permissions, cert_pem, key_pem, shared_key, 4,
            content, bytes(range(16)), work, "shared-stream",
        )
        verify_envelope_and_payload(
            shared_cms, shared_seed, permissions, cert_pem, key_pem, shared_key, 1,
            b"fr-FR", bytes(range(16, 32)), work, "shared-string",
        )
        shared_output.write_bytes(
            make_pdf(shared_cms, shared_key, shared_cms, shared_key, shared_default=True)
        )
        print(f"wrote {distinct_output} and {shared_output}; OpenSSL verified CMS envelopes and AESV2 payloads")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(f"usage: {sys.argv[0]} DISTINCT.pdf SHARED_CONTROL.pdf")
    main(pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]))
